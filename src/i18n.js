export function getLanguage(code) {
  return languages.find((language) => language.code === code) || languages[0];
}

export function getTranslations(code) {
  return translations[code] || translations.ar;
}

export function applyLanguage(code) {
  const language = getLanguage(code);

  document.documentElement.lang = language.code;
  document.documentElement.dir = language.rtl ? "rtl" : "ltr";

  localStorage.setItem("nexora-language", language.code);

  return language;
}

export function getSavedLanguage() {
  const saved = localStorage.getItem("nexora-language");

  if (saved && languages.some((language) => language.code === saved)) {
    return saved;
  }

  return "ar";
}
